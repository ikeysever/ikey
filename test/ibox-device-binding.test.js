'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
test('iBOX binding requires project owner, factory credential and atomic unique key',()=>{
 const server=fs.readFileSync(path.join(__dirname,'../server.js'),'utf8');
 const html=fs.readFileSync(path.join(__dirname,'../public/project-devices.html'),'utf8');
 const js=fs.readFileSync(path.join(__dirname,'../public/project-devices.js'),'utf8');
 const store=fs.readFileSync(path.join(__dirname,'../gen3-auth/sheets-store.js'),'utf8');
 assert.match(server,/app\.post\('\/api\/projects\/:projectId\/devices\/bind',requireProjectUser/);
 assert.match(server,/project\.created_by_user_id!==req\.projectUser\.user_id/);
 assert.match(server,/factoryDeviceCall\('factoryDeviceCredentialGet'/);
 assert.match(server,/factoryDeviceCall\('factoryDeviceBind'/);
 assert.match(server,/factoryDeviceCall\('factoryDeviceList'/);
 assert.match(server,/credential_kdf==='scrypt-n16384-r8-p1'/);
 assert.match(server,/crypto\.timingSafeEqual\(actual,expected\)/);
 assert.match(server,/actor_user_id=req\.projectUser\.user_id/);
 assert.match(store,/factoryDeviceCall:async\(action,payload\)/);
 assert.doesNotMatch(server.slice(server.indexOf("app.post('/api/projects/:projectId/devices/bind'"),server.indexOf('// Device pre-registration')),/table:'Devices'|table:'Project_Devices'|password_hash/);
 assert.match(server,/process\.env\.IKEY_DEVICE_BINDING_ENABLED!=='true'/);
 assert.match(server,/DEVICE_BINDING_DISABLED/);
 assert.match(server,/DEVICE_ALREADY_BOUND/);
 assert.match(html,/id="verify-bind-device"/);
 assert.match(html,/id="bind-feedback" role="alert"/);
 assert.match(js,/feedback\.textContent=e\.message/);
 assert.match(js,/credentials:'same-origin'/);
 assert.doesNotMatch(js,/localStorage\.setItem\(/);
 new Function(js);
});
