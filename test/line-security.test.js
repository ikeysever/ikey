'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {verifyWebhookSignature,createOAuthTransaction,buildAuthorizationUrl,validateIdTokenClaims}=require('../lib/line-security');
const secret='test-channel-secret';
const body=Buffer.from('{"events":[]}');
const signature=crypto.createHmac('sha256',secret).update(body).digest('base64');
assert.equal(verifyWebhookSignature(body,signature,secret),true);
assert.equal(verifyWebhookSignature(body,signature+'x',secret),false);
assert.equal(verifyWebhookSignature(Buffer.from('{}'),signature,secret),false);
const tx=createOAuthTransaction();
assert.equal(tx.state.length>20,true);
assert.equal(tx.nonce.length>20,true);
assert.equal(tx.challenge.length>20,true);
const url=new URL(buildAuthorizationUrl({channelId:'1234567890',redirectUri:'https://ikey.onrender.com/api/line/callback',state:tx.state,nonce:tx.nonce,challenge:tx.challenge}));
assert.equal(url.searchParams.get('state'),tx.state);
assert.equal(url.searchParams.get('code_challenge_method'),'S256');
const now=Math.floor(Date.now()/1000);
const claims={iss:'https://access.line.me',aud:'1234567890',sub:'Utest',nonce:tx.nonce,iat:now-10,exp:now+300};
assert.equal(validateIdTokenClaims(claims,{channelId:'1234567890',nonce:tx.nonce,now}),true);
assert.equal(validateIdTokenClaims({...claims,nonce:'wrong'},{channelId:'1234567890',nonce:tx.nonce,now}),false);
assert.equal(validateIdTokenClaims({...claims,exp:now-1},{channelId:'1234567890',nonce:tx.nonce,now}),false);
console.log('LINE security primitive tests passed');
